#!/usr/bin/env python3
"""PreToolUse guard: Claude never signs, approves or resets ADLC gates, and never edits evidence.

Backs up the permission rules in .claude/settings.json, which only match command prefixes.
Reads the hook payload on stdin; exit 2 blocks the tool call and shows stderr to Claude.
Authority files (routing, thresholds, ...) are left to the settings "ask" rules.
"""
import json
import re
import sys

# Shell commands that change gate state or record a person's decision.
BLOCKED_COMMANDS = [
    (r"adlc\.py\b.*\b(sign|approve|reset-gates|simulate)\b", "scripts/adlc.py sign/approve/reset-gates/simulate"),
    (r"\bmake\b.*\bsimulate\b", "make simulate (approves every gate with simulated approvers)"),
    (r"/lifecycle/gates/[^\s'\"]*/(sign|approve)\b", "POST /lifecycle/gates/*/sign|approve"),
    (r"/lifecycle/gates/reset\b", "POST /lifecycle/gates/reset"),
    (r"/usecases/[^\s'\"]+/(submit|classification/confirm)\b", "use-case submit / classification confirm (persona decisions)"),
    (r"/changes/[^\s'\"]+/decide\b", "change request decision (CAB)"),
    (r"lifecycle\.(sign|approve|reset_gates|simulate|sim_approvals)\s*\(", "direct lifecycle sign/approve/reset call"),
    (r"usecase\.(submit|confirm_classification)\s*\(", "direct use-case persona decision"),
]

EVIDENCE = re.compile(r"(^|/)evidence/")


def block(reason: str) -> None:
    print(
        f"Blocked by ADLC guard: {reason}. Gates are signed by people as personas in the UI "
        "(see CLAUDE.md). Tell the user what is ready to sign instead.",
        file=sys.stderr,
    )
    sys.exit(2)


def main() -> None:
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return
    tool = payload.get("tool_name", "")
    inp = payload.get("tool_input") or {}

    if tool == "Bash":
        cmd = inp.get("command", "")
        for pattern, label in BLOCKED_COMMANDS:
            if re.search(pattern, cmd):
                block(label)
    elif tool in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        path = inp.get("file_path") or inp.get("notebook_path") or ""
        if EVIDENCE.search(path):
            block("evidence/** is generated by the engine, never hand-edited")


if __name__ == "__main__":
    main()
